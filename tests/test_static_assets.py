import re
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
STATIC = ROOT / "web" / "static"
# a named colour is a whole word: white-space and --er-greyscale-white are not colours
RAW_COLOUR = re.compile(r"#[0-9a-fA-F]{3,8}\b|\brgba?\(|\bhsla?\(|(?<![\w-])(?:white|black|red|blue|green|gray|grey)(?![\w-])")


def test_the_tokens_file_is_the_design_systems():
    css = (STATIC / "er-tokens.css").read_text()
    assert css.startswith("/* Generated by scripts/emit-css.ts")   # verbatim copy, source noted below it
    assert "--er-ui-text-primary-text: #0a3235;" in css and '[data-theme="dark"]' in css


def test_the_app_stylesheet_has_no_raw_colour():
    css = (STATIC / "app.css").read_text()
    offenders = [l for l in css.splitlines() if RAW_COLOUR.search(l) and "/*" not in l]
    assert offenders == []


def test_the_sidebar_stylesheet_has_no_raw_colour_and_cuts_a_long_name():
    css = (STATIC / "nav.css").read_text()
    assert [l for l in css.splitlines() if RAW_COLOUR.search(l) and "/*" not in l] == []
    assert re.search(r"\.rail-dataset \{[^}]*text-overflow: ellipsis;", css)
    assert 'html[data-nav="closed"] #rail' in css


def test_the_sidebar_builder_touches_no_storage_and_no_document():
    js = (STATIC / "nav.js").read_text()
    assert "localStorage" not in js and "document." not in js and "window." not in js


def test_fonts_are_self_hosted_with_a_fallback_and_optional_display():
    css = (STATIC / "fonts" / "roboto.css").read_text()
    assert "font-weight: 400 700;" in css and "roboto.woff2" in css
    assert (STATIC / "fonts" / "roboto.woff2").stat().st_size > 5000
    assert css.count("font-display: optional;") == 1
    assert not (STATIC / "fonts" / "roboto-400.woff2").exists()
    app = (STATIC / "app.css").read_text()
    assert 'Roboto, system-ui, "Helvetica Neue", Arial, sans-serif' in app
    html = (ROOT / "web" / "templates" / "index.html").read_text()
    assert "fonts.googleapis.com/css2?family=Inter" not in html and "/static/fonts/roboto.css" in html and "/static/er-tokens.css" in html


def test_the_page_builders_pass_their_node_tests():
    if not shutil.which("node"):
        pytest.skip("node is not installed")
    r = subprocess.run(["node", "--test", *sorted(str(p.relative_to(ROOT)) for p in (ROOT / "tests" / "js").glob("*.test.js"))], cwd=ROOT, capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr


def test_the_page_is_a_sidebar_beside_the_content_under_a_band_that_only_names_the_app():
    html = (ROOT / "web" / "templates" / "index.html").read_text()
    assert 'id="rail"' in html and 'id="crumbs"' not in html
    band = html[html.index('<header id="band">'):html.index("</header>")]
    assert 'alt="EarthRanger"' in band and 'data-i18n="shell.appName"' in band and "version" not in band   # the version is at the sidebar's foot
    assert "<button" not in band and "<select" not in band and band.count("<a ") == 1   # the lockup, home; all else is the sidebar's
    css = (STATIC / "app.css").read_text()
    assert "--band-h: 48px" in css and "#rail .rail-brand, #rail .rail-app { display: none; }" in css
    nav = (STATIC / "nav.css").read_text()
    assert "top: var(--band-h, 0px)" in nav and "calc(100vh - var(--band-h, 0px))" in nav   # 0 in the browser, which has no band
    assert "/static/nav.js?v={{ assets['nav.js'] }}" in html and "/static/nav.css?v={{ assets['nav.css'] }}" in html
    assert html.index("/static/nav.js") < html.index("/static/pages.js") < html.index("/static/app.js")
    assert "localStorage.sidenav" in html   # the fold state is set before anything paints


def test_the_page_builders_and_the_sidebar_touch_no_storage():
    for name in ("nav.js", "pages.js"):
        assert "localStorage" not in (STATIC / name).read_text(), name


@pytest.mark.parametrize("name", ["app.css", "nav.css"])
def test_a_stylesheets_braces_never_close_more_than_they_open(name):
    """A declaration left behind without its selector swallows the rule after it: the browser reads
    everything up to the next { as one bad selector and drops that rule (it took .modal once)."""
    css = re.sub(r"/\*.*?\*/", "", (STATIC / name).read_text(), flags=re.S)
    depth = 0
    for n, line in enumerate(css.splitlines(), 1):
        for ch in line:
            depth += (ch == "{") - (ch == "}")
            assert depth >= 0, f"{name}:{n} closes a block that was never opened"
    assert depth == 0, f"{name} ends with {depth} block(s) still open"
